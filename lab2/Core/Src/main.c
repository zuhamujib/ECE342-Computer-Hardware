#include "main.h"
#include "config.h"

#include <stdio.h>
#include <math.h>


int main(void)
{
  /* Reset of all peripherals. */
  HAL_Init();

  /* Configure the system clock */
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC3_Init();
  MX_USART3_UART_Init();
  MX_USB_OTG_FS_PCD_Init();
  MX_DAC_Init();

  uint16_t adc_res, mask = 0xff00; // can change the value of mask to test out the quantization error in the analog sine wave generated by DAC hardware with 
                                   // different number of bits: 2 (0xfffc), 4 (0xfff0), 6 (0xffc0), 8 (0xff00)
  char message[100];
  
  //  ADC example
  HAL_ADC_Start(&hadc3);
  HAL_ADC_PollForConversion(&hadc3, 100);
  adc_res = HAL_ADC_GetValue(&hadc3);
  sprintf(message, "adc_res=%d\r\n", adc_res);
  print_msg(message);
  
  // DAC example
  HAL_DAC_Init(&hdac);
  HAL_DAC_Start(&hdac, DAC_CHANNEL_1);
  HAL_DAC_SetValue(&hdac, DAC_CHANNEL_1, DAC_ALIGN_12B_R, 255);

  while (1)
  {
   // Part 2: Converting analog signals from the oscilloscope to digital discrete values printed using the UART serial port to the hercules utility
   HAL_ADC_Start(&hadc3); // starts conversion in ADC hardware from the gpio A4 pin
   HAL_ADC_PollForConversion(&hadc3, 100); // now we want to wait for the ADC conversion to complete
   adc_res = HAL_ADC_GetValue(&hadc3);	// return ADC conversion results
   sprintf(message, "adc_res = %d\n", adc_res);	// print into hercules by sending into the serial port
   print_msg(message);

   // Part 3: Converting the digital discrete values generated from the ADC hardware back to an analog sine wave and probing output onto an oscilloscope
   HAL_DAC_Init(&hdac);  
   HAL_DAC_Start(&hdac, DAC_CHANNEL_1); // starting the conversion in DAC hardware from the ADC hardware results to the D5 pin output
   uint16_t masked_adc_res = adc_res & mask;  // Masking lower bits to test the quatization error
   HAL_DAC_SetValue(&hdac, DAC_CHANNEL_1, DAC_ALIGN_12B_R, adc_res); // converts the discrete values to analog wave

   // Note: For part 3 make sure to comment out any possible lines of code that would cause delays in the DAC conversion for example: initialization/print/delay
   //       as they would cause to lower the sample rate than what it is currently set on the hardware board and thus create an inaccurate analog sine wave
   
    HAL_GPIO_TogglePin(LD2_GPIO_Port, LD2_Pin);
    HAL_Delay(500); // modify the sampling rate at lower frequencies to prevent aliasing
  }
 }
